async def _assemble_daily_puzzle(
    day: date,
    *,
    user: Optional[UserContext],
    include_guess_opening: bool,
    cache: CacheBackend,
) -> DailyPuzzleResponse:
    popular_pool = await _load_popular_pool(day, cache, settings)
    user_lists: Optional[MediaListCollection] = None
    recent_ids: List[int] = []

    if user:
        user_lists = await _fetch_user_lists(cache, user)
        recent_ids = await _get_recent_media(cache, user.user_id)

    pool = _build_candidate_pool(popular_pool, user_lists, recent_ids)
    base_seed = day.isoformat()
    if user:
        base_seed = f"{base_seed}:{user.user_id}"

    selected_ids: set[int] = set()
    recorded_ids: List[int] = []
    families = anime_seasons.series_groups(popular_pool)

    def family_ids(media_id: int) -> set[int]:
        return families.get(media_id, {media_id})

    anidle_candidate = _choose_media_from_pool(base_seed, "anidle", pool, selected_ids)
    anidle_media = await _load_media_details(anidle_candidate.id, cache, settings)
    selected_ids.update(family_ids(anidle_media.id))
    if anidle_media.id not in recorded_ids:
        recorded_ids.append(anidle_media.id)
    anidle_bundle = AnidlePuzzleBundle(
        mediaId=anidle_media.id,
        puzzle=_build_anidle(anidle_media),
        solution=_build_solution(anidle_media),
    )

    # Easy/Medium/Hard rounds draw from thirds of the full popularity ranking,
    # so a personalised pool keeps the same difficulty meaning.
    # Sequels are skipped: their answer is one specific season, which a
    # player naming the show would miss.
    round_pool = [media for media in pool if not _is_sequel(media)] or pool
    tiers = _popularity_tiers([media for media in popular_pool if not _is_sequel(media)] or popular_pool or pool)
    poster_tiers = _popularity_tiers(popular_pool or pool)

    def remember(media: Media) -> None:
        selected_ids.update(family_ids(media.id))
        if media.id not in recorded_ids:
            recorded_ids.append(media.id)

    poster_rounds: List[PosterZoomRound] = []
    for order, difficulty in enumerate(ROUND_DIFFICULTIES, start=1):
        candidate = _choose_tiered(base_seed, "poster_zoomed", pool, poster_tiers, difficulty, selected_ids)
        poster_media = await _load_media_details(candidate.id, cache, settings)
        remember(poster_media)
        poster_round = _build_poster_round(media=poster_media, order=order, difficulty=difficulty)
        poster_round.meta.seriesTitles = anime_seasons.series_titles(poster_media, popular_pool, families)
        poster_round.meta.seasonOptions = anime_seasons.season_options(poster_media, popular_pool, families)
        poster_rounds.append(poster_round)

    poster_bundle = PosterZoomPuzzleBundle(
        mediaId=poster_rounds[0].mediaId,
        puzzle=PosterZoomGame(spec=POSTER_ROUNDS, rounds=poster_rounds),
        solution=poster_rounds[0].solution,
    )

    synopsis_rounds: List[RedactedSynopsisRound] = []
    synopsis_primary: Optional[Media] = None
    for order, difficulty in enumerate(ROUND_DIFFICULTIES, start=1):
        for attempt in range(8):
            if not _tier_candidates(round_pool, tiers, difficulty, selected_ids):
                break
            candidate = _choose_tiered(
                base_seed, "redacted_synopsis", round_pool, tiers, difficulty, selected_ids, attempt=attempt
            )
            synopsis_media = await _load_media_details(candidate.id, cache, settings)
            synopsis_round = _build_synopsis_round(synopsis_media, order=order, difficulty=difficulty)
            remember(synopsis_media)
            if synopsis_round:
                synopsis_rounds.append(synopsis_round)
                synopsis_primary = synopsis_primary or synopsis_media
                break
    if len(synopsis_rounds) != len(ROUND_DIFFICULTIES) or synopsis_primary is None:
        raise ValueError("Unable to build three redacted synopsis rounds with different anime")
    # Legacy top-level fields mirror round 1 for clients that predate rounds.
    synopsis_game = _build_synopsis(synopsis_primary)
    synopsis_game.rounds = synopsis_rounds
    synopsis_bundle = RedactedSynopsisPuzzleBundle(
        mediaId=synopsis_primary.id,
        puzzle=synopsis_game,
        solution=synopsis_rounds[0].solution,
    )

    character_bundle: Optional[CharacterSilhouettePuzzleBundle] = None
    character_rounds: List[CharacterGuessRound] = []
    character_media_by_id: dict[int, Media] = {}
    tried_for_characters: set[int] = set()
    for order, difficulty in enumerate(ROUND_DIFFICULTIES, start=1):
        entries: List[CharacterGuessEntry] = []
        for attempt in range(CHARACTERS_PER_ROUND * 4):
            if len(entries) >= CHARACTERS_PER_ROUND:
                break
            excluded = selected_ids | tried_for_characters
            if not _tier_candidates(round_pool, tiers, 1, excluded):
                break
            candidate = _choose_tiered(
                # Every character round uses popular shows; the round difficulty
                # comes from how the art is hidden (black and white, close-up,
                # mosaic), not from obscure characters.
                base_seed, f"character_silhouette:{order}", round_pool, tiers, 1, excluded, attempt=attempt
            )
            tried_for_characters.update(family_ids(candidate.id))
            character_media = await _load_media_details(candidate.id, cache, settings)
            edge = _featured_character_edge(character_media, set())
            if edge is not None:
                entries.append(_character_entry(character_media, edge, difficulty))
                character_media_by_id[character_media.id] = character_media
        if len(entries) < CHARACTERS_PER_ROUND:
            character_rounds = []
            break
        character_rounds.append(CharacterGuessRound(order=order, difficulty=difficulty, entries=entries))

    if character_rounds:
        for round_payload in character_rounds:
            for entry in round_payload.entries:
                remember(character_media_by_id[entry.mediaId])
        first_entry = character_rounds[0].entries[0]
        character_bundle = CharacterSilhouettePuzzleBundle(
            mediaId=first_entry.mediaId,
            puzzle=CharacterSilhouetteGame(
                spec=[
                    CharacterSilhouetteRound(
                        difficulty=round_payload.difficulty,
                        label=("Easy", "Medium", "Hard")[round_payload.difficulty - 1],
                        filter="none",
                    )
                    for round_payload in character_rounds
                ],
                answer=first_entry.animeAnswer,
                character=first_entry.character,
                rounds=character_rounds,
            ),
            solution=_build_solution(character_media_by_id[first_entry.mediaId]),
        )
    if not character_bundle:
        raise ValueError("Unable to build twelve character cards with different anime")

    guess_bundle: Optional[GuessOpeningPuzzleBundle] = None
    opening_rounds: List[GuessOpeningRound] = []
    if include_guess_opening:
        # Same popularity tiers as the other modes: Hard is a less popular but
        # established show, never this season's new releases. (The old
        # dedicated pool mixed in current-season shows and made Hard obscure.)
        candidate_pool = [media for media in pool if (media.status or "").upper() != "RELEASING"]
        if candidate_pool:
            required_rounds = len(ROUND_DIFFICULTIES)
            opening_tiers = poster_tiers
            tried_ids: set[int] = set()
            selected_for_opening: set[int] = set()
            for order, difficulty in enumerate(ROUND_DIFFICULTIES, start=1):
                for attempt in range(12):
                    if not _tier_candidates(
                        candidate_pool, opening_tiers, difficulty,
                        selected_ids | selected_for_opening | tried_ids,
                    ):
                        break
                    candidate = _choose_tiered(
                        base_seed,
                        "guess_the_opening",
                        candidate_pool,
                        opening_tiers,
                        difficulty,
                        selected_ids | selected_for_opening | tried_ids,
                        attempt=attempt,
                    )
                    tried_ids.update(family_ids(candidate.id))
                    opening_media = await _load_media_details(candidate.id, cache, settings)
                    opening_round = await _build_guess_opening_round(
                        opening_media,
                        cache,
                        order=order,
                        total_rounds=required_rounds,
                        difficulty=difficulty,
                    )
                    if opening_round:
                        opening_round.meta.seriesTitles = anime_seasons.series_titles(opening_media, popular_pool, families)
                        opening_round.meta.seasonOptions = anime_seasons.season_options(opening_media, popular_pool, families)
                        opening_rounds.append(opening_round)
                        selected_for_opening.update(family_ids(opening_round.mediaId))
                        break
            if len(opening_rounds) == required_rounds:
                selected_ids.update(selected_for_opening)
                for round_payload in opening_rounds:
                    if round_payload.mediaId not in recorded_ids:
                        recorded_ids.append(round_payload.mediaId)
                guess_bundle = GuessOpeningPuzzleBundle(
                    mediaId=opening_rounds[0].mediaId,
                    puzzle=GuessOpeningGame(rounds=list(opening_rounds)),
                    solution=opening_rounds[0].solution,
                )

    # One of each effect, shuffled by date independently of popularity tiers.
    modified_bundle: Optional[PosterZoomPuzzleBundle] = None
    modifications = list(MODIFICATIONS)
    random.Random(f"{base_seed}:poster-modifications").shuffle(modifications)
    modified_rounds: List[PosterZoomRound] = []
    modified_ids: set[int] = set()
    for order, difficulty in enumerate(ROUND_DIFFICULTIES, start=1):
        candidates = [
            media for media in pool
            if media.id in poster_tiers[difficulty]
            and media.id not in selected_ids | modified_ids
        ]
        if not candidates:
            break
        candidate = _select_media(f"{base_seed}:poster_modified:d{difficulty}", candidates)
        media = await _load_media_details(candidate.id, cache, settings)
        modified_ids.update(family_ids(media.id))
        modified_round = _build_poster_round(media=media, order=order, difficulty=difficulty)
        modified_round.meta.modification = modifications[order - 1]
        modified_round.meta.seriesTitles = anime_seasons.series_titles(media, popular_pool, families)
        modified_round.meta.seasonOptions = anime_seasons.season_options(media, popular_pool, families)
        modified_rounds.append(modified_round)
    if len(modified_rounds) == len(ROUND_DIFFICULTIES):
        selected_ids.update(modified_ids)
        recorded_ids.extend(r.mediaId for r in modified_rounds)
        modified_bundle = PosterZoomPuzzleBundle(
            mediaId=modified_rounds[0].mediaId,
            puzzle=PosterZoomGame(spec=POSTER_ROUNDS, rounds=modified_rounds),
            solution=modified_rounds[0].solution,
        )

    difficulty_hint: Optional[int] = None
    if user:
        preferences = await load_user_preferences(user.user_id)
        difficulty_hint = preferences.difficulty_level

    games = GamesPayload(
        anidle=anidle_bundle,
        poster_zoomed=poster_bundle,
        poster_modified=modified_bundle,
        redacted_synopsis=synopsis_bundle,
        character_silhouette=character_bundle,
        guess_the_opening=guess_bundle,
        difficulty_level=difficulty_hint,
    )

    if user:
        for media_id in recorded_ids:
            await _record_recent_media(cache, user.user_id, media_id)

    guess_opening_enabled = bool(
        guess_bundle
        and guess_bundle.puzzle.rounds
        and len(guess_bundle.puzzle.rounds) >= 3
    )

    return DailyPuzzleResponse(
        date=day,
        puzzle_id=f"daily:{day.isoformat()}",
        rules_version=CURRENT_RULES_VERSION,
        reset_at=datetime.combine(day + timedelta(days=1), time.min, tzinfo=timezone.utc),
        available_modes=["anidle", "poster_zoomed", "redacted_synopsis", "character_silhouette"] + (["guess_the_opening"] if guess_opening_enabled else []) + (["poster_modified"] if modified_bundle else []),
        games=games,
        guess_the_opening_enabled=guess_opening_enabled,
    )


async def get_daily_puzzle(
    day: date,
    *,
    user: Optional[UserContext] = None,
    include_guess_opening: bool = False,
) -> DailyPuzzleResponse:
    if day > datetime.now(timezone.utc).date():
        raise ValueError("Daily puzzles cannot be published for a future UTC date")
    # The date is the publication key. Personal lists and account identity are
    # deliberately excluded so every player sees the same immutable set.
    session_factory = get_session_factory()
    async with session_factory() as session:
        published = await session.get(DailyPuzzleSet, day)
        if published is not None:
            return _daily_response(published)
    if day < datetime.now(timezone.utc).date():
        raise LookupError(f"No published daily puzzle exists for {day.isoformat()}")
    return await publish_daily_puzzle(day, include_guess_opening=include_guess_opening)


async def publish_daily_puzzle(
    day: date,
    *,
    include_guess_opening: bool = False,
    replace_legacy: bool = False,
) -> DailyPuzzleResponse:
    """Generate and store the set for `day` unless one is already published.

    Used for today by `get_daily_puzzle` and for past days by the archive
    backfill (`python -m app.puzzles.backfill`). A current-format set is never
    replaced. With `replace_legacy`, a set stored under an older rules version
    is regenerated in the current format (an explicit, operator-run upgrade).
    """
    if day > datetime.now(timezone.utc).date():
        raise ValueError("Daily puzzles cannot be published for a future UTC date")
    session_factory = get_session_factory()
    async with session_factory() as session:
        published = await session.get(DailyPuzzleSet, day)
        if published is not None and (
            not replace_legacy or published.rules_version == CURRENT_RULES_VERSION
        ):
            return _daily_response(published)
        replacing = published is not None

    cache = await _get_cache()
    generated = await _assemble_daily_puzzle(
        day, user=None, include_guess_opening=include_guess_opening, cache=cache
    )
    modes = ["anidle", "poster_zoomed", "redacted_synopsis", "character_silhouette"]
    if generated.games.poster_modified is not None:
        modes.append("poster_modified")
    if generated.guess_the_opening_enabled:
        modes.append("guess_the_opening")
    reset_at = datetime.combine(day + timedelta(days=1), time.min, tzinfo=timezone.utc)
    content = generated.model_dump(mode="json", exclude={"puzzle_id", "rules_version", "reset_at", "available_modes", "mode_puzzle_ids"})
    async with session_factory() as session:
        if replacing:
            row = await session.get(DailyPuzzleSet, day)
            if row is not None and row.rules_version != CURRENT_RULES_VERSION:
                row.reset_at = reset_at
                row.rules_version = CURRENT_RULES_VERSION
                row.content = content
                row.available_modes = modes
                await session.commit()
        else:
            session.add(
                DailyPuzzleSet(
                    puzzle_date=day,
                    reset_at=reset_at,
                    rules_version=CURRENT_RULES_VERSION,
                    content=content,
                    available_modes=modes,
                )
            )
            try:
                await session.commit()
            except IntegrityError:
                # A parallel request published first; use its winning snapshot.
                await session.rollback()
    async with session_factory() as session:
        published = await session.get(DailyPuzzleSet, day)
        if published is None:
            raise RuntimeError("Daily puzzle publication did not persist")
        return _daily_response(published)


def daily_round_max_points(content: dict[str, Any], modes: Sequence[str]) -> dict[str, List[int]]:
    """Lightweight score projection, using only the stored daily snapshot."""
    maxima: dict[str, List[int]] = {}
    games = content.get("games") or {}
    for mode in modes:
        if mode not in {"poster_zoomed", "poster_modified", "guess_the_opening"}:
            maxima[mode] = [3000] if mode == "anidle" else [1000, 1000, 1000]
            continue
        rounds = ((games.get(mode) or {}).get("puzzle") or {}).get("rounds") or []
        points = []
        for entry in rounds:
            meta = entry.get("meta") or {}
            release = str(meta.get("season") or "").upper()
            has_year = bool(meta.get("year") or re.search(r"\b\d{4}\b", release))
            has_season = release.split(" ")[0] in {"WINTER", "SPRING", "SUMMER", "FALL"}
            base = 1000 if mode == "guess_the_opening" else 600
            options = meta.get("seasonOptions") or []
            has_number_bonus = len(options) > 1 and meta.get("seasonNumber") in options
            points.append(base + (100 if has_year else 0) + (100 if has_year and has_season else 0) + (200 if has_number_bonus else 0))
        maxima[mode] = points or [1000, 1000, 1000]
    return maxima


def _daily_response(row: DailyPuzzleSet) -> DailyPuzzleResponse:
    content = dict(row.content)
    modes = list(row.available_modes)
    response = DailyPuzzleResponse.model_validate({
        **content,
        "puzzle_id": f"daily:{row.puzzle_date.isoformat()}",
        "rules_version": row.rules_version,
        "reset_at": row.reset_at,
        "available_modes": modes,
        "mode_puzzle_ids": {mode: f"daily:{row.puzzle_date.isoformat()}:{mode}:v{row.rules_version}" for mode in modes},
    })
    # The guess budget and hint cadence are tuning, not puzzle content: serve
    # the current values even for sets published under older defaults.
    anidle = response.games.anidle.puzzle
    if anidle.rules is not None and anidle.rules.version == "2":
        anidle.rules = AnidleRules()
    return response
