def _offset_from_digest(digest: bytes, index: int, margin: float) -> tuple[float, float]:
    start = (index * 4) % len(digest)
    chunk = digest[start : start + 4]
    if len(chunk) < 4:
        chunk = (chunk + digest)[:4]
    raw_x = int.from_bytes(chunk[:2], "big") / 65535
    raw_y = int.from_bytes(chunk[2:], "big") / 65535
    lower = margin * 100.0
    upper = 100.0 - lower
    span = max(upper - lower, 0.0)
    offset_x = lower + raw_x * span
    offset_y = lower + raw_y * span
    return offset_x, offset_y


def _build_poster_crop_stages(media: Media, difficulty: int = 0) -> List[PosterCropStage]:
    cover = media.coverImage
    image_ref = ""
    if cover:
        image_ref = (
            getattr(cover, "extraLarge", None)
            or getattr(cover, "large", None)
            or getattr(cover, "medium", None)
            or ""
        )
    seed = f"poster:{media.id}:{image_ref}"
    digest = hashlib.sha256(seed.encode("utf-8")).digest()
    tiered = POSTER_ZOOM_SCALES.get(difficulty)
    if tiered:
        # Rounds v3 never zooms out to the whole poster (titles are printed on
        # most covers); the full art is only shown on the results screen.
        margins = (0.22, 0.16, 0.1)
        return [
            PosterCropStage(scale=scale, offset_x=x, offset_y=y)
            for index, scale in enumerate(tiered)
            for x, y in [_offset_from_digest(digest, index, margins[min(index, 2)])]
        ]
    scales = [1.65, 1.25, 1.0]
    stages: List[PosterCropStage] = []
    for index, scale in enumerate(scales):
        if index == len(scales) - 1:
            stages.append(PosterCropStage(scale=1.0, offset_x=50.0, offset_y=50.0))
            continue
        margin = 0.22 if index == 0 else 0.12
        offset_x, offset_y = _offset_from_digest(digest, index, margin)
        stages.append(PosterCropStage(scale=scale, offset_x=offset_x, offset_y=offset_y))
    return stages


def _poster_release_year(media: Media) -> Optional[int]:
    if media.seasonYear:
        return media.seasonYear
    start_date = media.startDate or {}
    year = start_date.get("year") if isinstance(start_date, dict) else None
    if isinstance(year, int):
        return year
    return None


def _poster_release_season(media: Media) -> Optional[str]:
    season = (media.season or "").replace("_", " ").strip()
    if not season:
        return None
    normalized = season.title()
    release_year = _poster_release_year(media)
    if release_year:
        return f"{normalized} {release_year}"
    return normalized


