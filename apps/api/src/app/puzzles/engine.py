def _poster_difficulty_bucket(media: Media, reference_year: int) -> int:
    year_bucket = 2
    release_year = _poster_release_year(media)
    if release_year is not None:
        if release_year >= reference_year - 2:
            year_bucket = 0
        elif release_year >= reference_year - 6:
            year_bucket = 1
    popularity = media.popularity or 0
    if popularity >= 150_000:
        pop_bucket = 0
    elif popularity >= 80_000:
        pop_bucket = 1
    else:
        pop_bucket = 2
    return min(year_bucket, pop_bucket)


def _sort_poster_candidates(candidates: Sequence[Media], reference_year: int) -> List[Media]:
    def sort_key(media: Media) -> Tuple[int, int, int, int]:
        bucket = _poster_difficulty_bucket(media, reference_year)
        popularity = media.popularity or 0
        release_year = _poster_release_year(media) or 0
        return (bucket, -popularity, -release_year, media.id)

    return sorted(candidates, key=sort_key)


def _select_poster_candidates(
    *,
    day: date,
    pool: Sequence[Media],
    required: int = 3,
) -> List[Media]:
    if not pool:
        return []

    reference_year = day.year
    sorted_pool = _sort_poster_candidates(pool, reference_year)
    buckets: dict[int, List[Media]] = {0: [], 1: [], 2: []}
    for media in sorted_pool:
        bucket = _poster_difficulty_bucket(media, reference_year)
        buckets.setdefault(bucket, []).append(media)

    selected: List[Media] = []
    selected_ids: set[int] = set()

    for bucket in (0, 1, 2):
        for candidate in buckets.get(bucket, []):
            if candidate.id in selected_ids:
                continue
            selected.append(candidate)
            selected_ids.add(candidate.id)
            break
        if len(selected) >= required:
            break

    if len(selected) < required:
        for candidate in sorted_pool:
            if candidate.id in selected_ids:
                continue
            selected.append(candidate)
            selected_ids.add(candidate.id)
            if len(selected) >= required:
                break

    if len(selected) < required:
        for candidate in pool:
            if candidate.id in selected_ids:
                continue
            selected.append(candidate)
            selected_ids.add(candidate.id)
            if len(selected) >= required:
                break

    return selected[:required]


def _tokenize_synopsis(text: str) -> tuple[List[str], List[int]]:
    tokens: List[str] = []
    word_indices: List[int] = []
    for match in TOKEN_PATTERN.finditer(text):
        token = match.group(0)
        tokens.append(token)
        if WORD_PATTERN.fullmatch(token):
            word_indices.append(len(tokens) - 1)
    return tokens, word_indices


def _mask_title_variants(tokens: List[str], word_indices: List[int], variants: Sequence[str]) -> set[int]:
    masked: set[int] = set()
    if not variants or not word_indices:
        return masked

    word_sequence = [tokens[index].casefold() for index in word_indices]

    for variant in sorted(set(variants), key=len, reverse=True):
        variant_words = [word.casefold() for word in WORD_PATTERN.findall(variant)]
        if not variant_words:
            continue
        start = 0
        max_start = len(word_sequence) - len(variant_words)
        while start <= max_start:
            if word_sequence[start : start + len(variant_words)] == variant_words:
                for offset in range(len(variant_words)):
                    masked.add(word_indices[start + offset])
                start += len(variant_words)
            else:
                start += 1
    return masked

def _deserialize_cached_image(payload: Any) -> Optional[Tuple[bytes, str]]:
    if not isinstance(payload, dict):
        return None
    encoded = payload.get("data")
    if not isinstance(encoded, str):
        return None
    try:
        decoded = base64.b64decode(encoded)
    except (binascii.Error, ValueError):
        return None
    mime = payload.get("mime") or "image/jpeg"
    return decoded, mime


def _normalize_hint_count(value: Any) -> int:
    try:
        hints_value = int(value)
    except (TypeError, ValueError):
        return 0
    if hints_value < 0:
        return 0
    return hints_value


def _resolve_poster_hint_round(hints_used: int, total_rounds: int) -> int:
    if total_rounds <= 0:
        return 1
    return max(1, min(total_rounds, hints_used + 1))


def _compute_clarity_level(hint_round: int, total_rounds: int) -> float:
    if total_rounds <= 1:
        return 1.0
    progress = (hint_round - 1) / max(1, total_rounds - 1)
    min_clarity = 0.2
    normalized = min_clarity + (1 - min_clarity) * progress
    return max(0.0, min(1.0, round(normalized, 2)))


def _apply_crop_stage(poster: Image.Image, stage: PosterCropStage) -> Image.Image:
    width, height = poster.size
    if width <= 0 or height <= 0:
        return poster

    scale = stage.scale if stage.scale and stage.scale > 0 else 1.0
    crop_width = width / scale
    crop_height = height / scale

    if crop_width <= 0 or crop_height <= 0:
        return poster

    center_x = (stage.offset_x / 100.0) * width
    center_y = (stage.offset_y / 100.0) * height

    max_left = max(0.0, width - crop_width)
    max_top = max(0.0, height - crop_height)
    left = min(max_left, max(0.0, center_x - (crop_width / 2)))
    top = min(max_top, max(0.0, center_y - (crop_height / 2)))
    right = left + crop_width
    bottom = top + crop_height

    cropped = poster.crop((left, top, right, bottom))
    if cropped.size == poster.size:
        return cropped

    return cropped.resize(poster.size, resample=POSTER_RESAMPLE)


async def _load_poster_source(
    media: Media, cache: CacheBackend, settings: Settings
) -> Tuple[bytes, str]:
    cache_key = f"poster-image-source:{media.id}"
    cached = await cache.get(cache_key)
    cached_image = _deserialize_cached_image(cached)
    if cached_image:
        return cached_image

    cover = media.coverImage or CoverImage()
    image_url = getattr(cover, "extraLarge", None) or getattr(cover, "large", None)
    if not image_url:
        image_url = getattr(cover, "medium", None)
    if not image_url:
        raise PosterImageError("Poster image unavailable", status_code=404)

    try:
        async with httpx.AsyncClient(timeout=20.0) as client:
            response = await client.get(image_url)
            response.raise_for_status()
    except httpx.HTTPError as exc:
        logger.warning("Failed to fetch poster image for %s: %s", media.id, exc)
        raise PosterImageError("Unable to fetch poster image", status_code=502) from exc

    content = response.content
    mime = response.headers.get("content-type") or "image/jpeg"

    try:
        encoded = base64.b64encode(content).decode("ascii")
        await cache.set(
            cache_key,
            {"data": encoded, "mime": mime},
            settings.puzzle_cache_ttl_seconds,
        )
    except Exception as exc:  # pragma: no cover - cache failures shouldn't block gameplay
        logger.debug("Unable to cache poster source image: %s", exc)

    return content, mime


def _render_poster_variant(
    source: bytes,
    hint_round: int,
    total_rounds: int,
    crop_stage: Optional[PosterCropStage],
    max_blur: float = 12.0,
) -> Tuple[bytes, str]:
    clarity = _compute_clarity_level(hint_round, total_rounds)

    try:
        with Image.open(io.BytesIO(source)) as poster:
            poster = poster.convert("RGB")
            if crop_stage is not None:
                poster = _apply_crop_stage(poster, crop_stage)
            blur_radius = (1.0 - clarity) * max_blur
            if blur_radius > 0:
                poster = poster.filter(ImageFilter.GaussianBlur(radius=blur_radius))
            sharpness_factor = 0.4 + (clarity * 0.6)
            poster = ImageEnhance.Sharpness(poster).enhance(sharpness_factor)
            output = io.BytesIO()
            poster.save(output, format="JPEG", quality=90, optimize=True)
    except UnidentifiedImageError as exc:
        raise PosterImageError("Unable to process poster image", status_code=500) from exc

    return output.getvalue(), "image/jpeg"


async def generate_poster_image(media_id: int, hints: int, difficulty: int = 0) -> Tuple[bytes, str]:
    """Render a poster stage. `difficulty` 1-3 uses the rounds-v3 zoom ladder."""
    cache = await _get_cache()
    tier = difficulty if difficulty in POSTER_ZOOM_SCALES else 0
    requested_hints = _normalize_hint_count(hints)
    bucket = min(requested_hints, MAX_POSTER_HINTS)
    prefix = f"poster-image:v2:{media_id}" + (f":d{tier}" if tier else "")
    cache_key = f"{prefix}:{bucket}"

    cached = await cache.get(cache_key)
    cached_image = _deserialize_cached_image(cached)
    if cached_image:
        return cached_image

    media = await _load_media_details(media_id, cache, settings)
    crop_stages = _build_poster_crop_stages(media, tier)
    total_rounds = max(1, max(len(crop_stages), len(POSTER_ROUNDS)))
    max_hint_count = max(0, total_rounds - 1)
    effective_hints = min(bucket, max_hint_count)
    final_cache_key = f"{prefix}:{effective_hints}"

    if final_cache_key != cache_key:
        cached = await cache.get(final_cache_key)
        cached_image = _deserialize_cached_image(cached)
        if cached_image:
            return cached_image

    hint_round = _resolve_poster_hint_round(effective_hints, total_rounds)
    crop_stage: Optional[PosterCropStage] = None
    if crop_stages:
        crop_index = min(len(crop_stages) - 1, hint_round - 1)
        crop_stage = crop_stages[crop_index]

    source, _ = await _load_poster_source(media, cache, settings)
    variant_bytes, mime = _render_poster_variant(
        source,
        hint_round,
        total_rounds,
        crop_stage,
        # Tiered rounds rely on zoom (which already softens the crop); keep
        # only a light blur on early stages.
        max_blur=1.5 if tier else 12.0,
    )

    try:
        encoded = base64.b64encode(variant_bytes).decode("ascii")
        await cache.set(
            final_cache_key,
            {"data": encoded, "mime": mime},
            settings.puzzle_cache_ttl_seconds,
        )
    except Exception as exc:  # pragma: no cover - cache failures shouldn't block gameplay
        logger.debug("Unable to cache poster variant: %s", exc)

    return variant_bytes, mime


async def generate_modified_poster_image(media_id: int, hints: int, modification: Modification) -> Tuple[bytes, str]:
    cache = await _get_cache()
    bucket = min(2, max(0, hints))
    key = f"poster-modified:v2:{media_id}:{modification}:{bucket}"
    cached = _deserialize_cached_image(await cache.get(key))
    if cached:
        return cached
    media = await _load_media_details(media_id, cache, settings)
    source, _ = await _load_poster_source(media, cache, settings)
    try:
        content = render_modified_poster(source, modification, bucket, media_id)
    except (OSError, ValueError) as exc:
        raise PosterImageError("Unable to process poster image", status_code=500) from exc
    mime = "image/jpeg"
    await cache.set(key, {"data": base64.b64encode(content).decode("ascii"), "mime": mime}, settings.puzzle_cache_ttl_seconds)
    return content, mime


def _redact_description(
    media: Media,
) -> tuple[str, List[RedactedSynopsisSegment], List[int], List[str]]:
    if not media.description:
        return "", [], [], []

    clean_text = _strip_html(media.description)
    tokens, word_indices = _tokenize_synopsis(clean_text)
    if not tokens:
        return "", [], [], []

    variants = _title_variants(media)
    title_masked_indices = _mask_title_variants(tokens, word_indices, variants)

    word_count = len(word_indices)
    masked_indices: set[int] = set(title_masked_indices)
    if word_count == 1:
        masked_target = 1
    else:
        desired = math.ceil(word_count * 0.7)
        desired = max(desired, len(masked_indices))
        if word_count > 1:
            desired = min(desired, word_count - 1) if len(masked_indices) < word_count else word_count
        masked_target = max(1, min(desired, word_count))

    if len(masked_indices) < masked_target:
        remaining_indices = [index for index in word_indices if index not in masked_indices]
        if remaining_indices:
            seed_source = hashlib.sha256(f"synopsis:{media.id}".encode("utf-8")).hexdigest()
            seed = int(seed_source[:16], 16)
            rng = random.Random(seed)
            rng.shuffle(remaining_indices)
            needed = masked_target - len(masked_indices)
            for index in remaining_indices[:needed]:
                masked_indices.add(index)

    additional_indices = sorted(index for index in masked_indices if index not in title_masked_indices)
    title_indices_sorted = sorted(title_masked_indices)
    masked_word_indices = additional_indices + [index for index in title_indices_sorted if index not in additional_indices]

    segments = [
        RedactedSynopsisSegment(text=token, masked=index in masked_indices)
        for index, token in enumerate(tokens)
    ]
    masked_words = [segments[index].text for index in masked_word_indices]

    return clean_text.strip(), segments, masked_word_indices, masked_words


def _build_synopsis(media: Media) -> RedactedSynopsisGame:
    text, segments, masked_indices, masked_words = _redact_description(media)
    return RedactedSynopsisGame(
        spec=SYNOPSIS_ROUNDS,
        answer=_choose_answer(media),
        text=text,
        segments=segments,
        masked_word_indices=masked_indices,
        masked_words=masked_words,
    )


def _normalize_role(role: Optional[str]) -> Optional[str]:
    if not role:
        return None
    normalized = role.replace("_", " ").strip()
    if not normalized:
        return None
    return normalized.title()


def _character_name_variants(edge: MediaCharacterEdge) -> List[str]:
    names = [
        edge.node.name.userPreferred if edge.node and edge.node.name else None,
        edge.node.name.full if edge.node and edge.node.name else None,
        edge.node.name.native if edge.node and edge.node.name else None,
    ]
    variants: List[str] = []
    seen: set[str] = set()
    for value in names:
        if not value:
            continue
        normalized = value.strip()
        if not normalized:
            continue
        key = normalized.casefold()
        if key in seen:
            continue
        seen.add(key)
        variants.append(normalized)
    return variants


def _build_character_guess_game(media: Media) -> Optional[CharacterSilhouetteGame]:
    rounds_required = len(CHARACTER_GUESS_ROUND_CONFIG)
    if rounds_required <= 0:
        return None
    per_round = 4
    round_difficulties = [config["difficulty"] for config in CHARACTER_GUESS_ROUND_CONFIG]
    allocations = character_pool.build_round_pools(
        media,
        round_difficulties,
        per_round=per_round,
        max_candidates=per_round * 4,
    )
    if (
        not allocations
        or len(allocations) != rounds_required
        or any(len(edges) < per_round for edges in allocations)
    ):
        logger.debug(
            "Unable to allocate character pools for media %s", media.id
        )
        return None

    answer = _choose_answer(media)
    anime_aliases = _title_variants(media)
    spec_rounds: List[CharacterSilhouetteRound] = []
    rounds: List[CharacterGuessRound] = []

    for config, edges in zip(CHARACTER_GUESS_ROUND_CONFIG, allocations):
        entries: List[CharacterGuessEntry] = []
        for edge in edges:
            image = edge.node.image if edge.node else None
            image_url = None
            if image:
                image_url = image.large or image.medium
            if not image_url:
                return None
            name = (
                edge.node.name.full
                or edge.node.name.userPreferred
                or edge.node.name.native
                or "Unknown"
            )
            character_payload = CharacterSilhouetteCharacter(
                id=edge.node.id,
                name=name,
                image=image_url,
                role=_normalize_role(edge.role),
            )
            reveal = CharacterGuessReveal(
                label=config["label"],
                filter=config["filter"],
                description=config.get("description"),
            )
            entry = CharacterGuessEntry(
                character=character_payload,
                characterAnswer=name,
                characterAliases=_character_name_variants(edge),
                animeAnswer=answer,
                animeAliases=anime_aliases,
                reveal=reveal,
            )
            entries.append(entry)
        rounds.append(
            CharacterGuessRound(
                order=config["order"],
                difficulty=config["difficulty"],
                entries=entries,
            )
        )
        spec_rounds.append(
            CharacterSilhouetteRound(
                difficulty=config["difficulty"],
                label=config["label"],
                filter=config["filter"],
                description=config.get("description"),
            )
        )

    primary_character: Optional[CharacterSilhouetteCharacter] = None
    if rounds and rounds[-1].entries:
        primary_character = rounds[-1].entries[0].character
    elif rounds and rounds[0].entries:
        primary_character = rounds[0].entries[0].character
    if primary_character is None:
        return None

    return CharacterSilhouetteGame(
        spec=spec_rounds,
        answer=answer,
        character=primary_character,
        rounds=rounds,
    )


def _build_solution(media: Media) -> SolutionPayload:
    cover = media.coverImage
    cover_image = None
    if cover:
        cover_image = cover.extraLarge or cover.large or cover.medium
    synopsis: Optional[str] = None
    if media.description:
        clean = _strip_html(media.description).strip()
        if clean:
            max_length = 280
            if len(clean) > max_length:
                cutoff = clean.rfind(" ", 0, max_length)
                if cutoff <= 0:
                    cutoff = max_length
                synopsis = clean[:cutoff].rstrip() + "…"
            else:
                synopsis = clean

    streaming_links: List[SolutionStreamingLink] = []
    for link in media.externalLinks or []:
        site = link.get("site")
        url = link.get("url")
        if site and url and site in STREAMING_SITES:
            streaming_links.append(SolutionStreamingLink(site=site, url=url))

    return SolutionPayload(
        titles=media.title,
        coverImage=cover_image,
        synopsis=synopsis,
        aniListUrl=f"https://anilist.co/anime/{media.id}",
        streamingLinks=streaming_links,
    )


async def _build_guess_opening_round(
    media: Media,
    cache: CacheBackend,
    *,
    order: Optional[int] = None,
    total_rounds: Optional[int] = None,
    difficulty: Optional[int] = None,
) -> Optional[GuessOpeningRound]:
    cache_key = f"animethemes:clip:v3:{media.id}"

    async def creator() -> dict:
        clip = await animethemes.find_opening_clip(_title_variants(media), anilist_id=media.id)
        if clip:
            return {"clip": asdict(clip)}
        return {"missing": True}

    clip_data = await cache.remember(cache_key, settings.puzzle_cache_ttl_seconds, creator)
    if clip_data.get("missing"):
        return None

    clip_model = animethemes.OpeningClip(**clip_data["clip"])

    meta = GuessOpeningMeta(
        seasonNumber=anime_seasons.season_number(media),
        songTitle=clip_model.song_title,
        artist=clip_model.artist,
        sequence=clip_model.sequence,
        season=f"{media.season} {media.seasonYear}" if media.seasonYear and media.season else None,
        genres=[genre for genre in media.genres if genre][:4],
        year=_poster_release_year(media),
        roundOrder=order,
        roundTotal=total_rounds,
    )
    length = clip_model.length_seconds or 90
    shift = random.Random(f"opening-window:{media.id}").uniform(0.0, OPENING_CLIP_MAX_SHIFT)
    window_start, window_end = (edge + round(shift) for edge in OPENING_CLIP_WINDOW)
    if length <= window_end:
        # Short clips: keep a 30-second window as late as the clip allows.
        window_end = float(length)
        window_start = max(0.0, window_end - (OPENING_CLIP_WINDOW[1] - OPENING_CLIP_WINDOW[0]))
    clip_payload = OpeningClip(
        audioUrl=clip_model.audio_url or clip_model.video_url,
        videoUrl=clip_model.video_url,
        mimeType="audio/mpeg" if clip_model.audio_url and clip_model.audio_url.endswith(".mp3") else None,
        lengthSeconds=length,
        startSeconds=window_start,
        endSeconds=window_end,
    )
    return GuessOpeningRound(
        order=order or 1,
        difficulty=difficulty,
        mediaId=media.id,
        spec=[round_spec.model_copy(deep=True) for round_spec in OPENING_ROUNDS],
        answer=_choose_answer(media),
        clip=clip_payload,
        meta=meta,
        solution=_build_solution(media),
    )


def _media_cache_key(media_id: int) -> str:
    return f"anilist:media:{media_id}"


def _search_cache_key(term: str, limit: int) -> str:
    """Cache key for an AniList title search, shared by search and Anidle evaluation."""
    # Preserve punctuation and every script: SQL's ASCII title normalization
    # would merge distinct upstream searches, including mixed-script titles.
    normalized = " ".join(term.split()).casefold()
    return f"anilist:search:v2:{limit}:{normalized}"


def _missing_media_cache_key(media_id: int) -> str:
    return f"anilist:media-missing:{media_id}"


# Unknown ids (typos, deleted or non-anime entries) are remembered briefly so
# repeated lookups do not each cost an AniList request.
MISSING_MEDIA_TTL_SECONDS = 3_600


async def _load_popular_pool(day: date, cache: CacheBackend, settings: Settings) -> List[Media]:
    """The popularity ranking, as full details records, fetched once per UTC day.

    The ranking is always today's (AniList keeps no history), so every target
    day generated today, including archive backfills, shares one fetch.
    v3: pool items carry every details field, and each is also stored under
    its media details key so building a set needs no per-anime lookups.
    """
    fetched_on = datetime.now(timezone.utc).date()
    cache_key = f"anilist:popular:v3:{fetched_on.isoformat()}"
    ttl = settings.anilist_cache_ttl_seconds

    async def creator() -> List[dict]:
        media = await anilist.fetch_popular_pool(pages=POPULAR_POOL_PAGES)
        raw = [m.model_dump(mode="json") for m in media]
        for item in raw:
            await cache.set(_media_cache_key(item["id"]), item, ttl)
        return raw

    raw_media = await cache.remember(cache_key, ttl, creator)
    return [Media.model_validate(item) for item in raw_media]


async def _prefetch_media_details(
    media_ids: Sequence[int], cache: CacheBackend, settings: Settings
) -> dict[int, Media]:
    """Details for `media_ids` from the cache, fetching every miss in one batch.

    Ids AniList does not know are left out of the result and remembered as
    missing for an hour. Search indexes are not touched here.
    """
    found: dict[int, Media] = {}
    to_fetch: List[int] = []
    for media_id in dict.fromkeys(int(value) for value in media_ids):
        raw = await cache.get(_media_cache_key(media_id))
        if raw is not None:
            found[media_id] = Media.model_validate(raw)
        elif await cache.get(_missing_media_cache_key(media_id)) is None:
            to_fetch.append(media_id)
    if not to_fetch:
        return found

    fetched = await anilist.fetch_media_details_batch(to_fetch)
    for media_id in to_fetch:
        media = fetched.get(media_id)
        if media is None:
            await cache.set(_missing_media_cache_key(media_id), True, MISSING_MEDIA_TTL_SECONDS)
            continue
        await cache.set(_media_cache_key(media_id), media.model_dump(mode="json"), settings.anilist_cache_ttl_seconds)
        found[media_id] = media
    return found


async def _warm_media_details(media_ids: Sequence[int], cache: CacheBackend, settings: Settings) -> None:
    """Best-effort `_prefetch_media_details` so later per-id loads hit the cache."""
    if not media_ids:
        return
    try:
        await _prefetch_media_details(media_ids, cache, settings)
    except Exception as exc:  # per-id loads still work (and report errors) without it
        logger.debug("Batch media prefetch failed: %s", exc)


async def _ingest_media_indices(media_items: Sequence[Media]) -> None:
    if not media_items:
        return
    session_factory = get_session_factory()
    async with session_factory() as session:
        try:
            for media in media_items:
                await title_index.ingest_media(session, media, _title_variants(media))
                await character_index.ingest_characters(
                    session, media.characters.edges if media.characters else []
                )
            await session.commit()
        except Exception:  # pragma: no cover - index warming must not break gameplay
            await session.rollback()
            logger.exception(
                "Failed to warm search indices for media %s", [media.id for media in media_items]
            )


async def _load_media_details_many(
    media_ids: Sequence[int], cache: CacheBackend, settings: Settings
) -> dict[int, Media]:
    """Like `_load_media_details` for many ids: at most one AniList request per 50 misses."""
    found = await _prefetch_media_details(media_ids, cache, settings)
    await _ingest_media_indices(list(found.values()))
    return found


async def _load_media_details(media_id: int, cache: CacheBackend, settings: Settings) -> Media:
    found = await _load_media_details_many([media_id], cache, settings)
    media = found.get(int(media_id))
    if media is None:
        raise LookupError(f"AniList has no anime with id {media_id}")
    return media


